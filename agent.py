"""
Phase 4 & Production Agent Architecture: Multi-Agent LangGraph Framework
=============================================================================================
Flow: User -> Router Agent -> [RAG | SQL | Web | Math | Python | LLM] -> Planner Agent -> Critic Agent -> Final Response

Optimizations & Features:
  - True Multi-Agent architecture.
  - SQL Agent for querying structured databases.
  - Planner/Synthesizer Agent to draft the response based on worker data.
  - Critic Agent to evaluate the response and enforce self-correction loops.
"""

